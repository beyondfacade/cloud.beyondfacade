it("참고 신호에 잘못 들어간 '잘 버텼습니다' 과거 사실은 바로 앞 확인된 사실 문단 끝으로 옮긴다", () => {
  const text = "[확인된 사실] 카페는 약했습니다. [참고 신호] 조치 소식은 없습니다. "
    + "감염병 시기에는 양식, 헬스장이 다른 업종보다 상대적으로 잘 버텼습니다. "
    + "[확인된 사실] 최저임금 때는 방향이 없었습니다. [참고 신호] 최저임금 시기에는 PC방이 상대적으로 잘 버텼습니다.";

  expect(gradedParagraphs(text)).toBe(
    "[확인된 사실]  \n카페는 약했습니다.  \n감염병 시기에는 양식, 헬스장이 다른 업종보다 상대적으로 잘 버텼습니다.\n\n"
    + "[참고 신호]  \n조치 소식은 없습니다.\n\n"
    + "[확인된 사실]  \n최저임금 때는 방향이 없었습니다.  \n최저임금 시기에는 PC방이 상대적으로 잘 버텼습니다.",
  ); // 옮기고 빈 참고 신호 문단은 없앤다
});

it("'잘 버틴 업종은' 꼴도 확인된 사실로 옮긴다", () => {
  expect(gradedParagraphs("[확인된 사실] 약했습니다. [참고 신호] 소식은 없습니다. 감염병 시기에 상대적으로 잘 버틴 업종은 양식이었습니다."))
    .toBe("[확인된 사실]  \n약했습니다.  \n감염병 시기에 상대적으로 잘 버틴 업종은 양식이었습니다.\n\n[참고 신호]  \n소식은 없습니다.");
});

it("같은 근거 표기가 연달아 오면 한 문단으로 합친다", () => {
  expect(gradedParagraphs("[확인된 사실] 방향이 없었습니다. [확인된 사실] 강세입니다. [참고 신호] 소식은 없습니다. [참고 신호] 약세일 수 있습니다."))
    .toBe("[확인된 사실]  \n방향이 없었습니다.  \n강세입니다.\n\n[참고 신호]  \n소식은 없습니다.  \n약세일 수 있습니다.");
});

it("앞에 확인된 사실 문단이 없으면 '잘 버텼습니다'를 옮기지 않는다", () => {
  expect(gradedParagraphs("[참고 신호] 소식은 없습니다. 양식이 상대적으로 잘 버텼습니다."))
    .toBe("[참고 신호]  \n소식은 없습니다.  \n양식이 상대적으로 잘 버텼습니다.");
});

it("앞머리 제목 줄은 그대로 둔다", () => {
  expect(gradedParagraphs("### 유사 사례\n\n[확인된 사실] 약했습니다. 회복했습니다."))
    .toBe("### 유사 사례\n\n[확인된 사실]  \n약했습니다.  \n회복했습니다.");
});

it("근거 표기가 없는 글(폴백 목록 등)은 건드리지 않는다", () => {
  const fallback = "### 유사 사례\n\n- **코로나19** (2020-01-20~2022-04-17)\n- **메르스** (2015-05-20~2015-12-23)";
  expect(gradedParagraphs(fallback)).toBe(fallback);
});
