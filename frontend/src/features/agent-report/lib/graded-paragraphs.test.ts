import { expect, it } from "vitest";
import { gradedParagraphs } from "./graded-paragraphs";

it("근거 표기마다 문단을 나누고 표기 뒤와 문장마다 줄을 바꾼다", () => {
  const text = "[확인된 사실] 카페는 약했습니다. 메르스 때도 2분기 약세였습니다. [참고 신호] 최근 30일 조치 소식은 없습니다. "
    + "다시 오면 약세일 수 있습니다. [확인된 사실] 최저임금은 시급 10,320원(+2.9%)입니다.";

  expect(gradedParagraphs(text)).toBe(
    "[확인된 사실]  \n카페는 약했습니다.  \n메르스 때도 2분기 약세였습니다.\n\n"
    + "[참고 신호]  \n최근 30일 조치 소식은 없습니다.  \n다시 오면 약세일 수 있습니다.\n\n"
    + "[확인된 사실]  \n최저임금은 시급 10,320원(+2.9%)입니다.",
  );
});

it("LLM이 나눈 문단·줄바꿈은 무시하고 표기 기준으로 다시 짠다", () => {
  expect(gradedParagraphs("[확인된 사실]\n약했습니다.\n\n다음 유형도 약했습니다.\n[참고 신호] 뉴스 15건이 있습니다."))
    .toBe("[확인된 사실]  \n약했습니다.  \n다음 유형도 약했습니다.\n\n[참고 신호]  \n뉴스 15건이 있습니다.");
});

it("앞머리 제목 줄은 그대로 둔다", () => {
  expect(gradedParagraphs("### 유사 사례\n\n[확인된 사실] 약했습니다. 회복했습니다."))
    .toBe("### 유사 사례\n\n[확인된 사실]  \n약했습니다.  \n회복했습니다.");
});

it("근거 표기가 없는 글(폴백 목록 등)은 건드리지 않는다", () => {
  const fallback = "### 유사 사례\n\n- **코로나19** (2020-01-20~2022-04-17)\n- **메르스** (2015-05-20~2015-12-23)";
  expect(gradedParagraphs(fallback)).toBe(fallback);
});
